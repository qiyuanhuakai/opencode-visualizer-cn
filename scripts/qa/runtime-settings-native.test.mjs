import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createPersistentStorage } from '../../electron/persistentStorage.js';
import { createElectronLegacySource } from '../../electron/legacyExportSource.mjs';
import { openLegacyExport, readLegacyExportPage } from '../../shared/runtime/migration/legacyExport.js';
import { liveSettingKey, encodeLiveSetting, decodeLiveSetting } from '../../shared/runtime/liveSettings.js';

test('live native saves and tombstones preserve frozen files and an open legacy export token', async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'vis-live-settings-source-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const root = path.join(directory, 'renderer-storage.json');
  const legacy = path.join(directory, 'renderer-settings.json');
  const initial = JSON.stringify({ 'opencode.drafts.composer.v1': 'original draft' });
  const oldSettings = JSON.stringify({ 'opencode.vis.runtime.bridgeUrl': 'ws://old.invalid/runtime' });
  await fs.writeFile(root, initial);
  await fs.writeFile(legacy, oldSettings);
  const source = createElectronLegacySource(root);
  const token = await openLegacyExport(source);
  const before = await readLegacyExportPage(source, { token });
  const file = path.join(directory, 'renderer-live-settings.json');
  const store = createPersistentStorage(file);
  const url = liveSettingKey('vis.runtime.bridgeUrl');
  const credentials = liveSettingKey('auth.credentials.v1');
  store.setItem(url, encodeLiveSetting('ws://127.0.0.1:35807/runtime'));
  store.setItem(credentials, encodeLiveSetting('synthetic-local-only-marker'));
  let reopened = createPersistentStorage(file);
  assert.deepEqual(decodeLiveSetting(reopened.getItem(url)), { kind: 'value', value: 'ws://127.0.0.1:35807/runtime' });
  reopened.setItem(url, encodeLiveSetting(null));
  reopened = createPersistentStorage(file);
  assert.deepEqual(decodeLiveSetting(reopened.getItem(url)), { kind: 'missing' });
  assert.equal(await fs.readFile(root, 'utf8'), initial);
  assert.equal(await fs.readFile(legacy, 'utf8'), oldSettings);
  const after = await readLegacyExportPage(source, { token });
  assert.deepEqual(after, before);
  assert.equal(JSON.stringify({ token, after }).includes('synthetic-local-only-marker'), false);
  assert.equal(JSON.stringify(after).includes('vis.live-settings.'), false);
});
