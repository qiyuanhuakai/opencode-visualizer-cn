/**
 * Task 46 — live SSH QA against a REAL sshd on a REAL login namespace.
 *
 * Registered happy invocation (from the plan):
 *   node scripts/qa/runtime-v090-live-ssh.mjs --isolated \
 *        --out .omo/evidence/vis-v090/task-46/ssh.json
 *
 * AC1 (real SSH host key verification, a real jump host, real reconnection) is graded
 * against the real sshd started by `runtime-v090-slurm-lab.mjs` — never a fake.
 *
 * Receiver contracts respected (task 26 / task 29, the receiver-contract lesson):
 *   - the ssh argv is a structured array spawned with shell:false, and every token is
 *     checked for NUL/CR/LF before it is handed to the spawn layer;
 *   - a secret travels as a 0600 FILE PATH, never as a value on the command line;
 *   - a connection is only reported ready after the target hello actually succeeds —
 *     ExitOnForwardFailure is an argv option, not readiness.
 */
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { execLab, startLab, stopLab } from './runtime-v090-slurm-lab.mjs';

/** Tokens that a shell would reinterpret; the receiver rejects these before any spawn. */
const SHELL_UNSAFE = /[\0\r\n]/;

export function parseArgs(argv) {
  const values = { isolated: false, case: 'happy' };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--isolated') values.isolated = true;
    else if (argument === '--case') values.case = argv[++index];
    else if (argument === '--out') values.out = argv[++index];
    else if (argument === '--runtime') values.runtime = argv[++index];
    else throw new Error(`Unknown argument: ${argument}`);
  }
  assert(values.isolated, '--isolated is required: this lane must never run against the production host');
  assert(['happy', 'failure'].includes(values.case), `--case must be happy|failure, got ${values.case}`);
  return values;
}

/** Mirrors task 26's guard: a structured argv where no token may contain NUL/CR/LF. */
export function buildSshArgv(options) {
  const argv = ['-o', 'RequestTTY=no', '-o', 'ForwardAgent=no', '-o', 'ExitOnForwardFailure=yes', '-o', 'IdentitiesOnly=yes'];
  argv.push('-o', `StrictHostKeyChecking=${options.strictHostKeyChecking ?? 'yes'}`);
  if (options.knownHostsFile !== undefined) argv.push('-o', `UserKnownHostsFile=${options.knownHostsFile}`);
  argv.push('-o', `ConnectTimeout=${options.connectTimeoutSeconds ?? 10}`);
  for (const identity of options.identityFiles ?? []) argv.push('-i', identity);
  if (options.proxyJump !== undefined) argv.push('-J', options.proxyJump);
  if (options.port !== undefined) argv.push('-p', String(options.port));
  if (options.forward !== undefined) argv.push('-L', `${options.forward.localHost ?? '127.0.0.1'}:${options.forward.localPort}:${options.forward.remoteHost}:${options.forward.remotePort}`);
  argv.push('--', options.target);
  for (const token of argv) assert(!SHELL_UNSAFE.test(token), 'argv token contains a shell-unsafe character (NUL/CR/LF)');
  return Object.freeze(argv);
}

function check(scenarios, name, observed, expected, detail) {
  assert.deepEqual(observed, expected, `${name}: ${detail ?? JSON.stringify(observed)}`);
  scenarios.push({ name, surface: 'live-ssh', assertions: [{ name, passed: true, observed, expected }] });
  console.log(`PASS ${name}`);
}

export async function runLiveSsh(options) {
  const scenarios = [];
  const receipts = [];
  const record = (name, receipt) => { receipts.push({ name, exitCode: receipt.exitCode, stdout: receipt.stdout.slice(0, 4000), stderr: receipt.stderr.slice(0, 4000) }); return receipt; };

  const lab = await startLab({ runtime: options.runtime, timeoutMs: options.timeoutMs });
  try {
    // ---------------------------------------------------------------- preconditions
    const sshdVersion = await execLab(lab, ['bash', '-c', '/usr/sbin/sshd -V 2>&1 | head -1']);
    check(scenarios, 'precondition: real sshd is running', sshdVersion.exitCode === 0 && /OpenSSH_/.test(`${sshdVersion.stdout}${sshdVersion.stderr}`), true, `${sshdVersion.stdout}${sshdVersion.stderr}`.trim());
    const hostKeys = await execLab(lab, ['bash', '-c', 'ls -1 /etc/ssh/ssh_host_*_key 2>/dev/null | wc -l']);
    check(scenarios, 'precondition: real host keys generated by ssh-keygen', Number(hostKeys.stdout.trim()) >= 2, true, hostKeys.stdout.trim());
    // A readiness PROBE, not a single sample: the daemon is started by the lab setup, so a
    // one-shot check can observe the instant before the bind lands. Poll until it listens.
    let listeners = null;
    for (let attempt = 0; attempt < 60; attempt += 1) {
      listeners = await execLab(lab, ['bash', '-c', 'nsenter --net=/var/run/netns/login ss -lnt 2>/dev/null | grep -c ":22 "']);
      if (listeners.exitCode === 0 && Number(listeners.stdout.trim()) >= 1) break;
      await new Promise((resolve) => setTimeout(resolve, 1000));
    }
    if (listeners === null || Number(listeners.stdout.trim()) < 1) {
      // A missing listener is a hard precondition failure; dump the real daemon state so the
      // artifact says WHY, instead of a bare count mismatch.
      const why = await execLab(lab, ['bash', '-c', 'echo "ps: $(ps -eo pid,args | grep [s]shd | tr \'\\n\' \'|\')"; echo "log: $(tail -3 /tmp/sshd-login.log 2>&1 | tr \'\\n\' \'|\')"; echo "nsenter: $(nsenter --net=/var/run/netns/login ss -lnt 2>&1 | tr \'\\n\' \'|\')"']);
      throw new Error(`sshd is not listening on the login namespace: ${why.stdout.trim()}`);
    }
    check(scenarios, 'precondition: sshd listens on the login namespace', Number(listeners.stdout.trim()) >= 1, true, listeners.stdout.trim());

    // A real keypair, and the guard is exercised on the real argv before any spawn.
    await execLab(lab, ['bash', '-c', 'install -d -m 700 /root/.ssh; [ -s /root/.ssh/id_ed25519 ] || ssh-keygen -t ed25519 -N "" -f /root/.ssh/id_ed25519 >/dev/null; grep -qf /root/.ssh/id_ed25519.pub /home/labuser/.ssh/authorized_keys || cat /root/.ssh/id_ed25519.pub >> /home/labuser/.ssh/authorized_keys']);
    const argv = buildSshArgv({ target: 'labuser@vislab-login', identityFiles: ['/root/.ssh/id_ed25519'], knownHostsFile: '/root/.ssh/known_hosts' });
    check(scenarios, 'receiver contract: ssh argv is a structured array with no shell-unsafe token', Array.isArray(argv) && argv.every((token) => typeof token === 'string' && token.length > 0 && !SHELL_UNSAFE.test(token)), true, argv.join(' '));
    check(scenarios, 'receiver contract: argv carries no secret value', argv.every((token) => !token.includes('PRIVATE KEY') && !/BEGIN OPENSSH/.test(token)), true, argv.join(' '));

    // ---------------------------------------------------------------- AC1a: real host key
    // First contact pins the real host key; a second connection must trust the SAME key.
    const first = record('hostkey: first contact pins the real host key', await execLab(lab, ['bash', '-c', [
      'set -e',
      'rm -f /root/.ssh/known_hosts',
      'ssh -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login \'echo FIRST_OK=$(hostname)\' 2>&1 | tail -1',
      // OpenSSH stores the entry hashed by default, so the pinned key is a |1| record.
      'echo "PINNED_LINES=$(grep -c . /root/.ssh/known_hosts)"',
      'echo "PINNED_KEY=$(awk \'{print $3}\' /root/.ssh/known_hosts | head -1 | cut -c1-20)"',
    ].join('\n')]));
    check(scenarios, 'hostkey: first contact succeeded', /FIRST_OK=vislab-login/.test(first.stdout), true, first.stdout.trim().slice(0, 240));
    check(scenarios, 'hostkey: a real host key was pinned in known_hosts', /PINNED_LINES=[1-9][0-9]*/.test(first.stdout) && /PINNED_KEY=AAAA/.test(first.stdout), true, first.stdout.trim().slice(0, 240));

    const second = record('hostkey: same key is trusted on reconnect', await execLab(lab, ['bash', '-c', [
      'set -e',
      'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login \'echo SECOND_OK=$(hostname)\' 2>&1 | tail -1',
    ].join('\n')]));
    check(scenarios, 'hostkey: reconnect trusts the pinned key', /SECOND_OK=vislab-login/.test(second.stdout), true, second.stdout.trim().slice(0, 240));

    // ---------------------------------------------------------------- AC1b: real jump host
    // The login node is a real bastion: the client connects to a compute node THROUGH it
    // with ProxyJump, so both hops are real SSH sessions with real host keys.
    const jump = record('jump: real ProxyJump through the login bastion to a compute node', await execLab(lab, ['bash', '-c', [
      'set -e',
      'ssh -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ConnectTimeout=10 -J labuser@vislab-login labuser@vislab-cn1 \'echo JUMP_TARGET=$(hostname) VIA=$SSH_CONNECTION\' 2>&1 | tail -2',
      'echo "KNOWN_HOSTS=$(grep -c . /root/.ssh/known_hosts)"',
      // A real forward through the bastion to the compute node's slurmd port.
      'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ExitOnForwardFailure=yes -L 39010:vislab-cn1:6818 -f -N labuser@vislab-login && echo FORWARD_ESTABLISHED',
      'echo "SLURMD_LISTENING=$(nsenter --net=/var/run/netns/cn1 ss -lnt 2>/dev/null | grep -c ":6818 " || true)"',
      'pkill -f "L 3901[0]:vislab-cn1:6818" 2>/dev/null || true',
      'sleep 1',
    ].join('\n')]));
    check(scenarios, 'jump: ProxyJump reached the compute node through the bastion', /JUMP_TARGET=vislab-cn1/.test(jump.stdout), true, jump.stdout.trim().slice(0, 240));
    check(scenarios, 'jump: both hops pinned real host keys', /KNOWN_HOSTS=[2-9][0-9]*/.test(jump.stdout), true, jump.stdout.trim().slice(0, 240));
    check(scenarios, 'jump: a real loopback forward through the bastion was established', /FORWARD_ESTABLISHED/.test(jump.stdout) && /SLURMD_LISTENING=1/.test(jump.stdout), true, jump.stdout.trim().slice(0, 240));

    // ---------------------------------------------------------------- AC1c: real reconnection
    // A live session is established, the login link is really broken, the failure is really
    // observed, and a brand-new session to the same target really succeeds afterwards.
    // Every ssh is wrapped in a hard `timeout`: a control master whose network died keeps
    // answering its local socket forever, and ConnectTimeout does NOT cover that wait, so
    // an unwrapped probe would wedge the whole lane.
    const reconnect = record('reconnect: session survives a real network break', await execLab(lab, ['bash', '-c', [
      'set -e',
      'rm -f /root/.ssh/cm-*',
      'timeout 30 ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o ControlMaster=yes -o ControlPath=/root/.ssh/cm-%r@%h:%p -o ControlPersist=600s -f -N labuser@vislab-login',
      'echo "SESSION_A=$(timeout 20 ssh -o ControlPath=/root/.ssh/cm-%r@%h:%p labuser@vislab-login \'echo $SSH_CLIENT::$HOSTNAME\')"',
      // A real break: bring the login node's veth down inside its own namespace.
      'nsenter --net=/var/run/netns/login ip link set p-login down',
      'sleep 3',
      // Observe the break with a FRESH connection (never the stale control path).
      // The capture pattern keeps `set -e` from aborting on the expected non-zero exit.
      'BREAK_RC=0',
      'timeout 10 ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ConnectTimeout=3 labuser@vislab-login true >/tmp/break.out 2>&1 || BREAK_RC=$?',
      'echo "BREAK_RC=$BREAK_RC"',
      'tail -1 /tmp/break.out',
      // Restore the link and prove a NEW session really reconnects to the same target.
      'nsenter --net=/var/run/netns/login ip link set p-login up',
      'sleep 4',
      'RECONNECT_RC=0',
      'timeout 25 ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ConnectTimeout=5 labuser@vislab-login \'echo SESSION_B=$SSH_CLIENT::$HOSTNAME\' >/tmp/reconnect.out 2>&1 || RECONNECT_RC=$?',
      'echo "RECONNECT_RC=$RECONNECT_RC"',
      'tail -1 /tmp/reconnect.out',
      'ssh -o ControlPath=/root/.ssh/cm-%r@%h:%p -O exit labuser@vislab-login >/dev/null 2>&1 || true',
      'rm -f /root/.ssh/cm-*',
    ].join('\n')]));
    check(scenarios, 'reconnect: a live session existed before the break', /SESSION_A=10\.99\.0\.1 [0-9]+ 22::vislab-login/.test(reconnect.stdout), true, reconnect.stdout.trim().slice(0, 240));
    check(scenarios, 'reconnect: the network break was really observed', /BREAK_RC=[1-9][0-9]*/.test(reconnect.stdout) && /No route to host|Connection refused|timed out|reset by peer|unreachable/i.test(reconnect.stdout), true, reconnect.stdout.trim().slice(0, 240));
    check(scenarios, 'reconnect: a new session really reconnected to the same target', /RECONNECT_RC=0/.test(reconnect.stdout) && /SESSION_B=10\.99\.0\.1 [0-9]+ 22::vislab-login/.test(reconnect.stdout), true, reconnect.stdout.trim().slice(0, 240));

    if (options.case === 'happy') {
      const versions = await execLab(lab, ['bash', '-c', 'cat /tmp/lab-versions.txt 2>/dev/null || /usr/sbin/sshd -V 2>&1 | head -1']);
      return {
        schemaVersion: 1, status: 'passed', task: 46, lane: 'happy', plan: 'vis-v090-unified-runtime',
        surface: 'live-ssh', lab: lab.descriptor,
        sshd: versions.stdout.trim(), scenarios,
        scenarioCount: scenarios.length, assertions: scenarios.reduce((total, entry) => total + entry.assertions.length, 0),
        receipts,
      };
    }
    return await failureLane(lab, scenarios);
  } finally {
    await stopLab(lab);
  }
}

/**
 * The named SSH failure classes. Each induces the failure for real and asserts a
 * located, typed diagnosis. `changed-key` is the load-bearing one: a changed host key
 * must be refused with a real warning, never silently accepted.
 */
async function failureLane(lab, scenarios) {
  const classes = [];
  const induce = async (name, command) => {
    const receipt = await execLab(lab, ['bash', '-c', command]);
    classes.push({ name, exitCode: receipt.exitCode, diagnosis: locate(receipt), stdout: receipt.stdout.slice(0, 4000), stderr: receipt.stderr.slice(0, 4000) });
    return receipt;
  };

  // 1. changed key — the login host key is rotated; the pinned client must refuse.
  const changed = await induce('changed-key', [
    'set +e',
    'ssh -o ControlPath=/root/.ssh/cm-%r@%h:%p -O exit labuser@vislab-login 2>/dev/null',
    'ssh-keygen -R vislab-login -f /root/.ssh/known_hosts >/dev/null 2>&1',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login true 2>&1 | head -1',
    'grep -q vislab-login /root/.ssh/known_hosts && echo "PINNED=yes" || echo "PINNED=no"',
    'ssh-keygen -t ed25519 -N "" -f /etc/ssh/ssh_host_ed25519_key.rotated >/dev/null 2>&1',
    'cp /etc/ssh/ssh_host_ed25519_key.rotated /etc/ssh/ssh_host_ed25519_key',
    'pkill -x sshd 2>/dev/null',
    'sleep 2',
    'nsenter --net=/var/run/netns/login --uts=/run/uts/login /usr/sbin/sshd -D -e >/tmp/sshd-login.log 2>&1 &',
    'sleep 4',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login true 2>&1 | head -3',
    'echo "CHANGED_RC=$?"',
  ].join('\n'));
  check(scenarios, 'failure changed-key: rotated host key refused with a located warning', /REMOTE HOST IDENTIFICATION HAS CHANGED|Host key verification failed/.test(changed.stdout + changed.stderr), true, locate(changed));

  // 2. bad credential — a wrong key must be refused, not fall back. The rotated host key
  // is re-pinned first so this leg really reaches the AUTH stage rather than failing earlier
  // on host-key verification.
  const badKey = await induce('bad-credential', [
    'set +e',
    'ssh-keygen -R vislab-login -f /root/.ssh/known_hosts >/dev/null 2>&1',
    'ssh -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login true >/dev/null 2>&1',
    'ssh-keygen -t ed25519 -N "" -f /tmp/wrong-key >/dev/null 2>&1',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /tmp/wrong-key -o BatchMode=yes -o ConnectTimeout=8 labuser@vislab-login true >/tmp/badkey.out 2>&1',
    'echo "BADKEY_RC=$?"',
    'tail -2 /tmp/badkey.out',
  ].join('\n'));
  check(scenarios, 'failure bad-credential: wrong key refused', /Permission denied/.test(badKey.stdout + badKey.stderr), true, locate(badKey));

  // 3. auth cancel — a connection the client aborts mid-handshake must not hang.
  const cancelled = await induce('auth-cancel', [
    'set +e',
    'timeout 6 ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ConnectTimeout=3 labuser@vislab-login "sleep 30" 2>&1 | head -1 &',
    'C=$!; sleep 2; kill -INT $C 2>/dev/null; wait $C 2>/dev/null; echo "CANCEL_RC=$?"',
  ].join('\n'));
  check(scenarios, 'failure auth-cancel: aborted connection terminated', /CANCEL_RC=/.test(cancelled.stdout + cancelled.stderr), true, locate(cancelled));

  // 4. port collision — a forward to an occupied LOCAL port must fail loudly. The port is
  // occupied by a first real forward in the same namespace the ssh client binds in, so the
  // second forward on that port is a genuine bind collision.
  const collision = await induce('port-collision', [
    'set +e',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ExitOnForwardFailure=yes -L 39011:vislab-cn1:6818 -f -N labuser@vislab-login',
    'echo "FIRST_FORWARD_RC=$?"',
    'echo "OCCUPIED=$(ss -lnt 2>/dev/null | grep -c ":39011 " || true)"',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ExitOnForwardFailure=yes -L 39011:vislab-cn1:6818 -f -N labuser@vislab-login >/tmp/collision.out 2>&1',
    'echo "COLLISION_RC=$?"',
    'tail -2 /tmp/collision.out',
    'pkill -f "L 3901[1]:vislab-cn1:6818" 2>/dev/null || true',
  ].join('\n'));
  check(scenarios, 'failure port-collision: occupied local port refused', /FIRST_FORWARD_RC=0/.test(collision.stdout) && /OCCUPIED=[1-9][0-9]*/.test(collision.stdout) && /COLLISION_RC=[1-9][0-9]*/.test(collision.stdout), true, locate(collision));

  // 5. target hello failure — a forward whose remote end refuses delivers NO hello bytes.
  //    This is the task-26 receiver-contract lesson: ExitOnForwardFailure=yes is an argv
  //    option, so a clean forward exit is NOT readiness. The client must observe an empty
  //    reply (EOF), never a hello, and therefore never report ready.
  const hello = await induce('target-hello-failure', [
    'set +e',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes -o ExitOnForwardFailure=yes -L 39012:127.0.0.1:1 -f -N labuser@vislab-login',
    'echo "FORWARD_RC=$?"',
    'REPLY=$(timeout 5 bash -c \'exec 3<>/dev/tcp/127.0.0.1/39012; head -c 16 <&3\' 2>/dev/null | od -An -c | tr -d " \\n")',
    'echo "HELLO_REPLY=[$REPLY]"',
    'pkill -f "L 3901[2]:127.0.0.1:1" 2>/dev/null || true',
  ].join('\n'));
  check(scenarios, 'failure target-hello-failure: silent forward target never delivers a hello', /FORWARD_RC=0/.test(hello.stdout) && /HELLO_REPLY=\[\]/.test(hello.stdout), true, locate(hello));

  // 6. shell-unsafe token — the receiver's own guard must reject a NUL/CR/LF token.
  let guardRejected = false;
  try {
    buildSshArgv({ target: 'labuser@vislab-login\nrm -rf /' });
  } catch (error) {
    guardRejected = /shell-unsafe/.test(error.message);
  }
  check(scenarios, 'failure shell-unsafe-token: receiver guard rejected a CR/LF token', guardRejected, true, 'buildSshArgv guard');

  // 7. laptop kill — the client dies; the server side must be diagnosable.
  const laptop = await induce('laptop-kill', [
    'set +e',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login "sleep 60" & C=$!',
    'sleep 3',
    'kill -9 $C 2>/dev/null',
    'sleep 2',
    'echo "SERVER_SIDE=$(nsenter --net=/var/run/netns/login ss -tnp 2>/dev/null | grep -c ":22 " || true)"',
    'ssh -o StrictHostKeyChecking=yes -o UserKnownHostsFile=/root/.ssh/known_hosts -o IdentitiesOnly=yes -i /root/.ssh/id_ed25519 -o BatchMode=yes labuser@vislab-login "echo STILL_ALIVE" 2>&1 | tail -1',
  ].join('\n'));
  check(scenarios, 'failure laptop-kill: server side diagnosed and still serving', /STILL_ALIVE/.test(laptop.stdout), true, locate(laptop));

  return {
    schemaVersion: 1, status: 'passed', task: 46, lane: 'failure', plan: 'vis-v090-unified-runtime',
    surface: 'live-ssh', lab: lab.descriptor, failureClasses: classes, scenarios,
    scenarioCount: scenarios.length, assertions: scenarios.reduce((total, entry) => total + entry.assertions.length, 0),
  };
}

function locate(receipt) {
  const lines = `${receipt.stdout}\n${receipt.stderr}`.split('\n').map((line) => line.trim()).filter(Boolean);
  return lines.find((line) => /error|fatal|refus|denied|CHANGED|verification|timed out|reset|in use|RC=/.test(line)) ?? lines[0] ?? `exit ${receipt.exitCode} with no output`;
}

/**
 * Writes a real failure artifact before exiting non-zero.
 *
 * The plan's hard rule: "缺namespace/daemon前置条件exit非零并取得CI真实artifact，mock不替代"
 * — a missing namespace/daemon precondition must exit non-zero AND still produce a real CI
 * artifact. So a failed lane never exits silently: it records the located reason, then
 * exits 1.
 */
function writeFailureArtifact(options, error) {
  if (!options.out) return;
  const out = path.resolve(options.out);
  mkdirSync(path.dirname(out), { recursive: true });
  const record = {
    schemaVersion: 1,
    status: 'failed',
    task: 46,
    plan: 'vis-v090-unified-runtime',
    surface: 'live-ssh',
    lane: options.case,
    isolated: options.isolated === true,
    failure: {
      kind: 'precondition-or-assertion',
      message: error instanceof Error ? error.message : String(error),
      stack: error instanceof Error ? error.stack : undefined,
    },
    recordedAt: new Date().toISOString(),
  };
  writeFileSync(out, `${JSON.stringify(record, null, 2)}\n`);
  console.error(`failure artifact written: ${out}`);
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  try {
    const report = await runLiveSsh(options);
    if (options.out) {
      const out = path.resolve(options.out);
      mkdirSync(path.dirname(out), { recursive: true });
      writeFileSync(out, `${JSON.stringify(report, null, 2)}\n`);
    }
    console.log(`\n${report.lane.toUpperCase()} LANE: ${report.scenarioCount} scenarios, ${report.assertions} assertions, all passed`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    writeFailureArtifact(options, error);
    process.exitCode = 1;
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await main();
}
